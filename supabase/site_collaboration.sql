-- Run after notes.sql, worker_lease.sql, and content_quality.sql.
-- Public visitors can read and append comments. Only allowlisted editor accounts
-- can change descriptions or notes; browser users receive no delete permission.

alter table public.links
  add column if not exists manually_edited boolean not null default false;
alter table public.notes
  add column if not exists manually_edited boolean not null default false;

create table if not exists public.content_comments (
  id bigint generated by default as identity primary key,
  target_type text not null check (target_type in ('link', 'note')),
  target_id bigint not null,
  video_id text not null references public.videos(video_id) on delete cascade,
  author_name text check (author_name is null or char_length(trim(author_name)) between 1 and 80),
  body text not null check (char_length(trim(body)) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists content_comments_target_created_idx
  on public.content_comments (target_type, target_id, created_at);

alter table public.content_comments enable row level security;
revoke all on public.content_comments from public, anon, authenticated;
grant select, insert on public.content_comments to anon, authenticated;
grant usage, select on sequence public.content_comments_id_seq to anon, authenticated;

drop policy if exists "Public can read content comments" on public.content_comments;
create policy "Public can read content comments"
  on public.content_comments for select to anon, authenticated using (true);

drop policy if exists "Visitors can add comments to existing content" on public.content_comments;
create policy "Visitors can add comments to existing content"
  on public.content_comments for insert to anon, authenticated
  with check (
    (target_type = 'link' and exists (
      select 1 from public.links l
       where l.id = target_id and l.video_id = content_comments.video_id
    ))
    or
    (target_type = 'note' and exists (
      select 1 from public.notes n
       where n.id = target_id and n.video_id = content_comments.video_id
    ))
  );

create table if not exists public.site_editors (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.site_editors enable row level security;
revoke all on public.site_editors from public, anon, authenticated;
grant all on public.site_editors to service_role;

create or replace function public.is_site_editor()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select exists (
    select 1 from public.site_editors where user_id = auth.uid()
  );
$$;
revoke all on function public.is_site_editor() from public, anon;
grant execute on function public.is_site_editor() to authenticated;

-- Remove any broad browser write policies before installing the editor-only rule.
do $$
declare
  policy_row record;
begin
  for policy_row in
    select schemaname, tablename, policyname
      from pg_policies
     where schemaname = 'public'
       and tablename in ('links', 'notes')
       and cmd in ('INSERT', 'UPDATE', 'DELETE', 'ALL')
  loop
    execute format('drop policy if exists %I on %I.%I',
                   policy_row.policyname, policy_row.schemaname, policy_row.tablename);
  end loop;
end;
$$;

alter table public.links enable row level security;
alter table public.notes enable row level security;
drop policy if exists "Public can read website links" on public.links;
create policy "Public can read website links"
  on public.links for select to anon, authenticated using (true);
drop policy if exists "Public can read notes" on public.notes;
create policy "Public can read notes"
  on public.notes for select to anon, authenticated using (true);

drop policy if exists "Allowlisted editors can update links" on public.links;
create policy "Allowlisted editors can update links"
  on public.links for update to authenticated
  using (public.is_site_editor()) with check (public.is_site_editor());
drop policy if exists "Allowlisted editors can update notes" on public.notes;
create policy "Allowlisted editors can update notes"
  on public.notes for update to authenticated
  using (public.is_site_editor()) with check (public.is_site_editor());

revoke insert, update, delete on public.links from public, anon, authenticated;
revoke insert, update, delete on public.notes from public, anon, authenticated;
grant select on public.links, public.notes to anon, authenticated;
grant update (description, manually_edited) on public.links to authenticated;
grant update (title, detail, manually_edited) on public.notes to authenticated;

-- Keep existing row IDs so their comments stay attached during AI refreshes.
-- Manual edits are preserved; commented items are kept even if a model omits them.
create or replace function public.replace_video_links(p_video_id text, p_rows jsonb)
returns integer
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  affected_rows integer;
begin
  if p_video_id is null or length(trim(p_video_id)) = 0 then
    raise exception 'p_video_id is required';
  end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' then
    raise exception 'p_rows must be a JSON array';
  end if;

  insert into public.links as existing (video_id, url, domain, description, category)
  select p_video_id, row_data.url, row_data.domain, row_data.description, row_data.category
    from jsonb_to_recordset(p_rows) as row_data(
      url text, domain text, description text, category text
    )
  on conflict (video_id, url) do update
    set domain = excluded.domain,
        description = case when existing.manually_edited
                           then existing.description else excluded.description end,
        category = case when existing.manually_edited
                        then existing.category else excluded.category end;

  delete from public.links l
   where l.video_id = p_video_id
     and not l.manually_edited
     and not exists (
       select 1 from jsonb_to_recordset(p_rows) as row_data(url text)
        where row_data.url = l.url
     )
     and not exists (
       select 1 from public.content_comments c
        where c.target_type = 'link' and c.target_id = l.id
     );
  get diagnostics affected_rows = row_count;
  return affected_rows;
end;
$$;

create or replace function public.replace_video_notes(p_video_id text, p_rows jsonb)
returns integer
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  affected_rows integer;
begin
  if p_video_id is null or length(trim(p_video_id)) = 0 then
    raise exception 'p_video_id is required';
  end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' then
    raise exception 'p_rows must be a JSON array';
  end if;

  insert into public.notes as existing (video_id, title, detail, category)
  select p_video_id, row_data.title, row_data.detail, row_data.category
    from jsonb_to_recordset(p_rows) as row_data(
      title text, detail text, category text
    )
  on conflict (video_id, title) do update
    set detail = case when existing.manually_edited
                      then existing.detail else excluded.detail end,
        category = case when existing.manually_edited
                        then existing.category else excluded.category end;

  delete from public.notes n
   where n.video_id = p_video_id
     and not n.manually_edited
     and not exists (
       select 1 from jsonb_to_recordset(p_rows) as row_data(title text)
        where row_data.title = n.title
     )
     and not exists (
       select 1 from public.content_comments c
        where c.target_type = 'note' and c.target_id = n.id
     );
  get diagnostics affected_rows = row_count;
  return affected_rows;
end;
$$;

revoke all on function public.replace_video_links(text, jsonb) from public, anon, authenticated;
revoke all on function public.replace_video_notes(text, jsonb) from public, anon, authenticated;
grant execute on function public.replace_video_links(text, jsonb) to service_role;
grant execute on function public.replace_video_notes(text, jsonb) to service_role;

