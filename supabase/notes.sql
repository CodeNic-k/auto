-- Track the Notes extraction separately from the existing website-link status.
-- Existing video rows become pending for note backfill; only Shorts are queried.
alter table public.videos
  add column if not exists notes_status text not null default 'pending';

alter table public.videos
  add column if not exists notes_error_message text;

alter table public.videos
  add column if not exists notes_processed_at timestamptz;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'videos_notes_status_check'
      and conrelid = 'public.videos'::regclass
  ) then
    alter table public.videos
      add constraint videos_notes_status_check
      check (notes_status in ('pending', 'done', 'failed'));
  end if;
end $$;

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  video_id text not null references public.videos(video_id) on delete cascade,
  title text not null,
  detail text not null,
  category text not null default 'Other'
    check (category in (
      'AI tools', 'Productivity', 'Design', 'Dev tools',
      'Privacy/Security', 'Free resources', 'Learning',
      'Entertainment', 'How-to & workflows', 'Other'
    )),
  created_at timestamptz not null default now(),
  unique (video_id, title)
);

alter table public.notes enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'notes'
      and policyname = 'Public can read notes'
  ) then
    create policy "Public can read notes"
      on public.notes for select to anon using (true);
  end if;
end $$;

grant usage on schema public to anon, service_role;
grant select on public.notes to anon;
grant all on public.notes to service_role;
grant usage, select on all sequences in schema public to service_role;

