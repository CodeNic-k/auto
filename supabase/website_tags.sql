-- Keep track of which videos support each automatic website tag. This lets a
-- refresh replace only that video's tag contribution while retaining tags
-- supported by other videos that feature the same website.
create table if not exists public.link_tag_sources (
  link_tag_id bigint not null references public.link_tags(id) on delete cascade,
  video_id text not null references public.videos(video_id) on delete cascade,
  primary key (link_tag_id, video_id)
);
create index if not exists link_tag_sources_video_id_idx
  on public.link_tag_sources (video_id);
alter table public.link_tag_sources enable row level security;
revoke all on public.link_tag_sources from public, anon, authenticated;
grant all on public.link_tag_sources to service_role;

alter table public.link_tags enable row level security;
revoke all on public.link_tags from public, anon, authenticated;
grant select, insert on public.link_tags to anon, authenticated;
grant update (status) on public.link_tags to authenticated;
grant usage, select on sequence public.link_tags_id_seq to anon, authenticated;

drop policy if exists "Public can read approved website tags" on public.link_tags;
create policy "Public can read approved website tags"
  on public.link_tags for select to anon, authenticated
  using (status = 'approved');

drop policy if exists "Editors can read all website tags" on public.link_tags;
create policy "Editors can read all website tags"
  on public.link_tags for select to authenticated
  using (public.is_site_editor());

drop policy if exists "Visitors can suggest website tags" on public.link_tags;
create policy "Visitors can suggest website tags"
  on public.link_tags for insert to anon, authenticated
  with check (
    source = 'user' and status = 'pending'
    and exists (select 1 from public.links l where l.id = link_id)
  );

drop policy if exists "Editors can add approved website tags" on public.link_tags;
create policy "Editors can add approved website tags"
  on public.link_tags for insert to authenticated
  with check (
    public.is_site_editor() and source = 'user' and status = 'approved'
    and exists (select 1 from public.links l where l.id = link_id)
  );

drop policy if exists "Editors can moderate website tags" on public.link_tags;
create policy "Editors can moderate website tags"
  on public.link_tags for update to authenticated
  using (public.is_site_editor()) with check (
    public.is_site_editor() and status in ('approved', 'rejected')
  );

create or replace function public.replace_video_link_tags(p_video_id text, p_rows jsonb)
returns integer
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  affected_rows integer := 0;
begin
  if p_video_id is null or length(trim(p_video_id)) = 0 then
    raise exception 'p_video_id is required';
  end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' then
    raise exception 'p_rows must be a JSON array';
  end if;

  -- Never replace the old AI set with an empty or invalid result. The worker
  -- will mark that video failed and it can be retried with the tags intact.
  if exists (
    select 1
      from jsonb_to_recordset(p_rows) as row_data(url text, tags jsonb)
     where jsonb_typeof(row_data.tags) <> 'array'
        or not exists (
          select 1
            from jsonb_array_elements_text(
              case when jsonb_typeof(row_data.tags) = 'array' then row_data.tags else '[]'::jsonb end
            ) as tag_data(tag)
           where char_length(trim(tag_data.tag)) between 2 and 40
             and trim(tag_data.tag) ~ '^[[:alnum:]][[:alnum:] &._+-]{0,39}$'
        )
  ) then
    raise exception 'Each website must have at least one valid functional tag';
  end if;

  if exists (
    select 1
      from jsonb_to_recordset(p_rows) as row_data(url text, tags jsonb)
     where (
       select count(distinct coalesce(vocab.preferred_tag, lower(trim(tag_data.tag))))
         from jsonb_array_elements_text(row_data.tags) as tag_data(tag)
         left join public.website_tag_aliases vocab
           on vocab.alias = lower(trim(tag_data.tag))
        where char_length(trim(tag_data.tag)) between 2 and 40
          and trim(tag_data.tag) ~ '^[[:alnum:]][[:alnum:] &._+-]{0,39}$'
     ) > 3
  ) then
    raise exception 'Each website can have at most three functional tags';
  end if;

  -- Replace this video's automatic tag contribution while leaving contributions
  -- from other videos and all user-added tags intact.
  delete from public.link_tag_sources where video_id = p_video_id;

  insert into public.link_tags (link_id, tag, source, status)
  select distinct l.id,
         coalesce(vocab.preferred_tag, lower(trim(tag_data.tag))),
         'ai', 'approved'
    from jsonb_to_recordset(p_rows) as row_data(url text, tags jsonb)
    join public.links l on l.url = row_data.url
    cross join lateral jsonb_array_elements_text(
      case when jsonb_typeof(row_data.tags) = 'array' then row_data.tags else '[]'::jsonb end
    ) as tag_data(tag)
    join public.link_sources ls on ls.link_id = l.id and ls.video_id = p_video_id
    left join public.website_tag_aliases vocab
      on vocab.alias = lower(trim(tag_data.tag))
   where char_length(trim(tag_data.tag)) between 2 and 40
     and trim(tag_data.tag) ~ '^[[:alnum:]][[:alnum:] &._+-]{0,39}$'
  on conflict do nothing;
  get diagnostics affected_rows = row_count;

  insert into public.link_tag_sources (link_tag_id, video_id)
  select distinct t.id, p_video_id
    from jsonb_to_recordset(p_rows) as row_data(url text, tags jsonb)
    join public.links l on l.url = row_data.url
    join public.link_sources ls on ls.link_id = l.id and ls.video_id = p_video_id
    cross join lateral jsonb_array_elements_text(row_data.tags) as tag_data(tag)
    left join public.website_tag_aliases vocab
      on vocab.alias = lower(trim(tag_data.tag))
    join public.link_tags t
      on t.link_id = l.id
     and lower(trim(t.tag)) = coalesce(vocab.preferred_tag, lower(trim(tag_data.tag)))
     and t.source = 'ai' and t.status = 'approved'
  on conflict do nothing;

  -- If the model identifies a previously suggested tag, that evidence is
  -- sufficient to approve it while retaining the original user submission.
  update public.link_tags t
     set status = 'approved'
    from jsonb_to_recordset(p_rows) as row_data(url text, tags jsonb)
    join public.links l on l.url = row_data.url
    cross join lateral jsonb_array_elements_text(
      case when jsonb_typeof(row_data.tags) = 'array' then row_data.tags else '[]'::jsonb end
    ) as tag_data(tag)
    left join public.website_tag_aliases vocab
      on vocab.alias = lower(trim(tag_data.tag))
   where l.id = t.link_id
     and lower(trim(t.tag)) = coalesce(vocab.preferred_tag, lower(trim(tag_data.tag)))
     and t.source = 'user'
     and t.status = 'pending';

  -- Keep the three best-supported automatic concepts per site. When several
  -- source videos describe a site, shared functions rank ahead of one-off tags.
  with ranked_ai_tags as (
    select t.id,
           row_number() over (
             partition by t.link_id
             order by count(s.video_id) desc, lower(t.tag), t.id
           ) as tag_rank
      from public.link_tags t
      join public.link_tag_sources s on s.link_tag_id = t.id
     where t.source = 'ai' and t.status = 'approved'
     group by t.id, t.link_id, t.tag
  ), excess_ai_tags as (
    select id from ranked_ai_tags where tag_rank > 3
  )
  delete from public.link_tags t
   using excess_ai_tags e
   where t.id = e.id;

  delete from public.link_tags t
   where t.source = 'ai'
     and not exists (
       select 1 from public.link_tag_sources s where s.link_tag_id = t.id
     );
  return affected_rows;
end;
$$;

revoke all on function public.replace_video_link_tags(text, jsonb) from public, anon, authenticated;
grant execute on function public.replace_video_link_tags(text, jsonb) to service_role;

notify pgrst, 'reload schema';
