-- Run after site_collaboration.sql and global_website_dedup.sql.
-- Website tags are independent of AI refreshes. Visitor additions are pending
-- until an allowlisted editor approves them.

create table if not exists public.link_tags (
  id bigint generated by default as identity primary key,
  link_id bigint not null references public.links(id) on delete cascade,
  tag text not null check (
    char_length(trim(tag)) between 2 and 40
    and tag ~ '^[[:alnum:]][[:alnum:] &._+-]{0,39}$'
  ),
  source text not null default 'user' check (source in ('ai', 'user')),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

create unique index if not exists link_tags_link_normalized_unique_idx
  on public.link_tags (link_id, lower(trim(tag)));
create index if not exists link_tags_approved_tag_idx
  on public.link_tags (lower(trim(tag)), link_id) where status = 'approved';

